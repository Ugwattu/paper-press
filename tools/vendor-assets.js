#!/usr/bin/env node
/* Copies self-hosted assets out of node_modules into the committed fonts/ and vendor/ folders (run: npm run vendor).
   End users never run this: the results are committed so GitHub Pages serves them as plain static files. */
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const root = path.join(__dirname, '..'), nm = path.join(root, 'node_modules');
const FONTS = [
  { pkg: 'inter', family: 'Inter', weights: [400, 500, 600, 700, 800, 900], subsets: ['latin'] },
  { pkg: 'jetbrains-mono', family: 'JetBrains Mono', weights: [400, 600, 700], subsets: ['latin'] },
  { pkg: 'noto-nastaliq-urdu', family: 'Noto Nastaliq Urdu', weights: [400, 700], subsets: ['arabic', 'latin'] }
];
const out = path.join(root, 'fonts'); fs.rmSync(out, { recursive: true, force: true }); fs.mkdirSync(out, { recursive: true });
let css = '/* Self-hosted fonts (generated by tools/vendor-assets.js from @fontsource packages, SIL OFL 1.1). Do not edit by hand. */\n';
for (const f of FONTS) {
  const base = path.join(nm, '@fontsource', f.pkg);
  for (const w of f.weights) {
    const src = fs.readFileSync(path.join(base, `${w}.css`), 'utf8');
    for (const m of src.matchAll(/\/\* ([\w-]+) \*\/\s*@font-face \{([^}]*)\}/g)) {
      const name = m[1], subset = (name.match(/-(latin-ext|latin|arabic|cyrillic-ext|cyrillic|greek-ext|greek|vietnamese)-\d+-normal$/) || [])[1];
      if (!f.subsets.includes(subset)) continue;
      const range = (m[2].match(/unicode-range:\s*([^;]+);/) || [])[1];
      fs.copyFileSync(path.join(base, 'files', name + '.woff2'), path.join(out, name + '.woff2'));
      css += `@font-face{font-family:'${f.family}';font-style:normal;font-weight:${w};font-display:swap;src:url(${name}.woff2) format('woff2');${range ? 'unicode-range:' + range + ';' : ''}}\n`;
    }
  }
  const lic = path.join(base, 'LICENSE'); if (fs.existsSync(lic)) fs.copyFileSync(lic, path.join(out, 'LICENSE-' + f.pkg + '.txt'));
}
fs.writeFileSync(path.join(out, 'fonts.css'), css);
const v = path.join(root, 'vendor'); fs.mkdirSync(v, { recursive: true });
const mj = fs.readFileSync(path.join(nm, 'mathjax', 'es5', 'tex-svg.js')), sri = 'sha384-' + crypto.createHash('sha384').update(mj).digest('base64');
fs.writeFileSync(path.join(v, 'mathjax-3.2.2-tex-svg.js'), mj);
fs.writeFileSync(path.join(v, 'README.md'), `# vendor/\n\n- \`mathjax-3.2.2-tex-svg.js\` — MathJax 3.2.2 (Apache-2.0), copied unmodified from the \`mathjax@3.2.2\` npm package.\n  SRI: \`${sri}\` (identical to the CDN copies, so one hash covers local, cdnjs and jsDelivr).\n  Regenerate with \`npm run vendor\`.\n`);
console.log('fonts:', fs.readdirSync(out).filter((x) => x.endsWith('.woff2')).length, 'woff2 files;', 'mathjax SRI', sri);
